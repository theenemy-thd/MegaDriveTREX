# Z80 bank-read stress: the Z80 sums 256 bytes of 68000 ROM through its bank window over and
# over and counts passes whose sum differs from the first one, while the 68000 keeps touching
# the Z80 area (YM2612 status reads), so a "safe" overclock keeps switching speed.
# Results: $FF8000 = Z80 passes, $FF8004 = Z80 mismatches, $FF8008 = 68000 loop count marker.
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'mkrom.py')).read()
exec(src[:src.index('# --- program ---')])

z80 = [0xF3, 0x31, 0x00, 0x1F, 0xCD, 0x26, 0x00, 0x22, 0x00, 0x10,
       0xCD, 0x26, 0x00, 0xED, 0x5B, 0x00, 0x10, 0xB7, 0xED, 0x52, 0x28, 0x07,
       0x2A, 0x04, 0x10, 0x23, 0x22, 0x04, 0x10,
       0x2A, 0x02, 0x10, 0x23, 0x22, 0x02, 0x10, 0x18, 0xE4,
       0x21, 0x00, 0x00, 0x01, 0x00, 0x80, 0x16, 0x00,
       0x0A, 0x5F, 0x19, 0x0C, 0x20, 0xFA, 0xC9]
assert len(z80) == 0x35

w(0x33FC,0x0100,0x00A1,0x1100)   # Z80 bus request
w(0x33FC,0x0100,0x00A1,0x1200)   # Z80 reset off
L('zw')
w(0x0839,0x0000,0x00A1,0x1100)   # btst #0,$A11100
bne('zw')
for i, b in enumerate(z80):      # move.b #b,$A00000+i
    w(0x13FC, b, 0x00A0, i)
for a in range(0x1000, 0x1006):  # clear results
    w(0x13FC, 0, 0x00A0, a)
w(0x33FC,0x0000,0x00A1,0x1200)   # Z80 reset on
w(0x33FC,0x0000,0x00A1,0x1100)   # release bus
w(0x3E3C,0x0040)
L('d0')
dbf(7,'d0')
w(0x33FC,0x0100,0x00A1,0x1200)   # Z80 reset off: Z80 runs
w(0x3C3C,0x00FF)                 # move.w #255,d6
L('m1')
w(0x1039,0x00A0,0x4000)          # move.b $A04000,d0 (YM2612 status: Z80 area)
w(0x3E3C,0x0060)                 # move.w #96,d7
L('m2')
w(0x5281)                        # addq.l #1,d1
dbf(7,'m2')
dbf(6,'m1')
w(0x33FC,0x0100,0x00A1,0x1100)   # Z80 bus request
L('zw2')
w(0x0839,0x0000,0x00A1,0x1100)
bne('zw2')
w(0x7000)                        # moveq #0,d0
w(0x1039,0x00A0,0x1003)          # passes hi
w(0xE148)                        # lsl.w #8,d0
w(0x1039,0x00A0,0x1002)          # passes lo
w(0x23C0,0x00FF,0x8000)
w(0x7000)
w(0x1039,0x00A0,0x1005)
w(0xE148)
w(0x1039,0x00A0,0x1004)
w(0x23C0,0x00FF,0x8004)
w(0x23C1,0x00FF,0x8008)
w(0x33FC,0x600D,0x00FF,0x8020)
L('end')
bra('end')

words = [0] * 0x400
code = assemble(0x200)
assert 0x200 + 2 * len(code) <= 0x700, hex(0x200 + 2 * len(code))
words[0:4] = [0x00FF, 0xFE00, 0x0000, 0x0200]
for v in range(2, 64):
    words[v * 2:v * 2 + 2] = [0x0000, 0x0700]
words[0x100:0x100 + len(code)] = code
words[0x380:0x385] = [0x33FC, 0x0BAD, 0x00FF, 0x8020, 0x60FE]
open('rom_z80bank.hex', 'w').write(''.join(('%04X' % x) + chr(10) for x in words))
print('ok', hex(0x200 + 2 * len(code)))
